P1      EQU 090H
P2      EQU 0A0H
P3      EQU 0B0H

ORG 0000H
LJMP MAIN

ORG 0003H
LJMP INT0_ISR

ORG 0030H

MAIN:

MOV P1,#0FFH
MOV P2,#00H
MOV P3,#0FFH

SETB 88H
SETB 0A8H
SETB 0AFH

MOV R7,#00H
MOV R6,#00H

LOOP:


SETB 0B6H
NOP
NOP
CLR 0B6H

WAIT1:
JB 0B7H,WAIT1



MOV A,R7
JZ DOWNMODE

UPMODE:
MOV A,R6
CJNE A,#42,INC1
SJMP READY

INC1:
INC R6
SJMP READY

DOWNMODE:
MOV A,R6
JZ READY
DEC R6

READY:

MOV A,P1
ADD A,R6

JNC OK1
MOV A,#255

OK1:
MOV P2,A
SJMP LOOP

INT0_ISR:

INC R7
MOV A,R7
ANL A,#01H
MOV R7,A

RETI

END
