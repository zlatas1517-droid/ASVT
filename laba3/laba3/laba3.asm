main proc
    xor esi, esi

outer_loop:
    cmp esi, N
    jge finish

    mov edi, esi
    inc edi

inner_loop:
    cmp edi, N
    jge next_i

    mov eax, esi
    imul eax, 32
    lea ebx, lines
    add ebx, eax

    mov eax, edi
    imul eax, 32
    lea ecx, lines
    add ecx, eax

    fld qword ptr [ebx+16]
    fsub qword ptr [ebx]
    fstp qword ptr [dx1]

