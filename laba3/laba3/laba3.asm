    mov dword ptr [edx+eax], 0

    mov ebx, edi
    imul ebx, N
    add ebx, esi
    imul ebx, 4
    mov dword ptr [edx+ebx], 0

next_j:
    inc edi
    jmp inner_loop

next_i:
    inc esi
    jmp outer_loop

finish:
    ret

main endp
end main